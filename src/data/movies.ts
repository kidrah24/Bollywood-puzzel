export function normalizeTitle(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function isMatchingMovie(guess: string, film: BollywoodFilm): boolean {
  const clean = normalizeTitle(guess);
  if (!clean) return false;
  if (clean === normalizeTitle(film.title)) return true;
  return film.aliases.some((alias) => normalizeTitle(alias) === clean);
}

export function getLocalDateKey(date: Date = new Date()): string {
  const y = date.getFullYear();
  const m = String(date.getMonth() + 1).padStart(2, '0');
  const d = String(date.getDate()).padStart(2, '0');
  return `${y}-${m}-${d}`;
}

export function getDailyCutNumber(date: Date = new Date()): number {
  const epoch = new Date(2026, 0, 1);
  const current = new Date(date.getFullYear(), date.getMonth(), date.getDate());
  const diffDays = Math.floor((current.getTime() - epoch.getTime()) / 86400000);
  return Math.max(1, diffDays + 1);
}

export function getDailyMovieIndex(date: Date = new Date()): number {
  const cutNum = getDailyCutNumber(date);
  return (cutNum - 1) % FEATURED_MOVIES.length;
}
